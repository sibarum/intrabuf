package sibarum.intrabuf.processor;

import sibarum.intrabuf.Compat;
import sibarum.intrabuf.HeaderRole;
import sibarum.intrabuf.Hex;
import sibarum.intrabuf.processor.MessageModel.FieldModel;
import sibarum.intrabuf.schema.Layout;
import sibarum.intrabuf.schema.ScalarKind;
import sibarum.intrabuf.schema.TypeRef;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import static sibarum.intrabuf.schema.Json.quote;

/**
 * Writes the source of one codec. The output is deliberately plain: one local per field, a bitset built with
 * constant masks, then one {@code IbWriter}/{@code IbReader} call per value, with loops only for collections.
 * Every name the generated code uses is fully qualified, and every local it introduces contains a {@code $}
 * except the {@code f_<component>} locals, so nothing can collide with a user's names.
 */
final class CodecGenerator {

    private static final String RT = "sibarum.intrabuf.";

    private final MessageModel m;
    private final int fingerprint;
    private final boolean snapshot;
    private final String buildVersion;
    private final Layout layout;
    private final Map<String, String> enumFields = new LinkedHashMap<>();
    private final StringBuilder sb = new StringBuilder();
    private int indent;
    private int tmp;

    CodecGenerator(MessageModel m, int fingerprint, boolean snapshot, String buildVersion) {
        this.m = m;
        this.fingerprint = fingerprint;
        this.snapshot = snapshot;
        this.buildVersion = buildVersion;
        this.layout = Layout.of(m.defs());
    }

    String generate() {
        // Methods first, so the enum value tables they need are known before the class header is written.
        String methods = methods();
        sb.setLength(0);
        indent = 0;
        if (!m.packageName().isEmpty()) {
            line("package " + m.packageName() + ";");
            line("");
        }
        if (m.header()) {
            headerClass(methods);
            return sb.toString();
        }
        line("/**");
        line(" * Codec for {@link " + m.javaName() + "}: schema {@code " + m.schemaName() + "} v" + m.major() + "." + m.minor()
                + ", " + m.compat() + ".");
        line(" * Generated by intrabuf; do not edit.");
        line(" */");
        line("@javax.annotation.processing.Generated(\"sibarum.intrabuf.processor.IntrabufProcessor\")");
        line("public final class " + m.codecSimpleName() + " extends " + RT + "MessageCodec<" + m.javaName() + "> {");
        indent++;
        line("");
        // Compile-time constants, so the processor can read them back from this class file when another module
        // nests this message.
        line("public static final String NAME = " + quote(m.schemaName()) + ";");
        line("public static final int ID = " + Hex.int32(m.id()) + ";");
        line("public static final int MAJOR = " + m.major() + ";");
        line("public static final int MINOR = " + m.minor() + ";");
        line("public static final int FINGERPRINT = " + Hex.int32(fingerprint) + ";");
        line("public static final boolean SNAPSHOT = " + snapshot + ";");
        line("public static final String BUILD_VERSION = " + quote(buildVersion) + ";");
        line("");
        line("public static final " + RT + "SchemaInfo SCHEMA = new " + RT + "SchemaInfo(NAME, " + quote(m.javaName())
                + ", ID, MAJOR, MINOR, " + RT + "Compat." + m.compat() + ", FINGERPRINT, SNAPSHOT, BUILD_VERSION);");
        line("");
        line("public static final " + m.codecSimpleName() + " CODEC = new " + m.codecSimpleName() + "();");
        line("");
        if (m.compat() == Compat.BACKWARD && layout.bitCount(m.minor()) > 0) {
            StringBuilder t = new StringBuilder();
            for (int minor = 0; minor <= m.minor(); minor++) {
                t.append(minor == 0 ? "" : ", ").append(layout.bitsetBytes(minor));
            }
            line("/** Bitset bytes written by each minor version. */");
            line("private static final int[] BITSET_BYTES = {" + t + "};");
        }
        for (Map.Entry<String, String> e : enumFields.entrySet()) {
            line("private static final " + e.getKey() + "[] " + e.getValue() + " = " + e.getKey() + ".values();");
        }
        line("");
        line("private " + m.codecSimpleName() + "() {");
        line("    super(SCHEMA);");
        line("}");
        line("");
        line("/** Encodes a complete payload. Same as {@code CODEC.encode(value)}. */");
        line("public static byte[] toBytes(" + m.javaName() + " value) {");
        line("    return CODEC.encode(value);");
        line("}");
        line("");
        line("/** Decodes a complete payload. Same as {@code CODEC.decode(payload)}. */");
        line("public static " + m.javaName() + " fromBytes(byte[] payload) {");
        line("    return CODEC.decode(payload);");
        line("}");
        sb.append(methods);
        indent--;
        line("}");
        return sb.toString();
    }

    private String methods() {
        indent = 1;
        line("");
        writeBody();
        line("");
        readBody();
        return sb.toString();
    }

    // ---- application headers -----------------------------------------------------------------------------------

    private void headerClass(String methods) {
        String type = m.javaName();
        line("/**");
        line(" * Header codec for {@link " + type + "}, an application header format ({@code " + m.schemaName() + "}).");
        line(" * Generated by intrabuf; do not edit.");
        line(" */");
        line("@javax.annotation.processing.Generated(\"sibarum.intrabuf.processor.IntrabufProcessor\")");
        line("public final class " + m.codecSimpleName() + " extends " + RT + "HeaderCodec<" + type + "> {");
        indent++;
        line("");
        line("public static final String NAME = " + quote(m.schemaName()) + ";");
        line("public static final int FINGERPRINT = " + Hex.int32(fingerprint) + ";");
        line("");
        line("public static final " + m.codecSimpleName() + " CODEC = new " + m.codecSimpleName() + "();");
        line("");
        for (Map.Entry<String, String> e : enumFields.entrySet()) {
            line("private static final " + e.getKey() + "[] " + e.getValue() + " = " + e.getKey() + ".values();");
        }
        line("");
        line("private " + m.codecSimpleName() + "() {");
        line("}");
        line("");

        // create(): role components from the schema, the application's from arguments.
        StringBuilder params = new StringBuilder(RT + "SchemaInfo schema$");
        StringBuilder args = new StringBuilder();
        for (FieldModel f : m.fields()) {
            HeaderRole role = m.roles().get(f.name());
            if (role == null) {
                params.append(", ").append(f.type().javaName()).append(' ').append(f.name());
            }
            args.append(args.isEmpty() ? "" : ", ").append(role == null ? f.name() : roleValue(role, f));
        }
        line("/** A header for a payload of {@code schema$}, with the application's fields as given. */");
        line("public static " + type + " create(" + params + ") {");
        line("    " + RT + "Header f$ = " + RT + "Header.of(schema$);");
        line("    return new " + type + "(" + args + ");");
        line("}");
        line("");

        // facts(): the role components as a Header.
        line("@Override");
        line("public " + RT + "Header facts(" + type + " h, int size) {");
        indent++;
        String fp = null;
        boolean fpBoxed = false;
        Map<HeaderRole, String> get = new java.util.EnumMap<>(HeaderRole.class);
        for (FieldModel f : m.fields()) {
            HeaderRole role = m.roles().get(f.name());
            if (role != null) {
                get.put(role, "h." + f.accessor() + "()");
                if (role == HeaderRole.FINGERPRINT) {
                    fp = "h." + f.accessor() + "()";
                    fpBoxed = !f.type().javaName().equals("int");
                }
            }
        }
        if (fpBoxed) {
            line("java.lang.Integer fp$ = " + fp + ";");
        }
        line("return new " + RT + "Header(" + get.get(HeaderRole.WIRE_VERSION) + ", " + get.get(HeaderRole.SNAPSHOT) + ", "
                + get.get(HeaderRole.COMPAT) + ", " + get.get(HeaderRole.SCHEMA_ID) + ", " + get.get(HeaderRole.MAJOR) + ", "
                + get.get(HeaderRole.MINOR) + ", " + (fpBoxed ? "fp$ != null, fp$ == null ? 0 : fp$" : "true, " + fp)
                + ", size);");
        indent--;
        line("}");
        sb.append(methods);
        indent--;
        line("}");
    }

    /** The expression {@code create()} fills a role component with, from {@code f$} (the facts) and {@code schema$}. */
    private static String roleValue(HeaderRole role, FieldModel f) {
        String j = f.type().javaName();
        return switch (role) {
            case WIRE_VERSION -> narrow("f$.wireVersion()", j, role);
            case SCHEMA_ID -> "f$.schemaId()";
            case MAJOR -> narrow("f$.major()", j, role);
            case MINOR -> narrow("f$.minor()", j, role);
            case COMPAT -> "f$.compat()";
            case SNAPSHOT -> "f$.snapshot()";
            // A primitive fingerprint is always carried, so carry the real one even where the built-in header omits it.
            case FINGERPRINT -> j.equals("int") ? "schema$.fingerprint()"
                    : "f$.hasFingerprint() ? java.lang.Integer.valueOf(f$.fingerprint()) : null";
        };
    }

    private static String narrow(String expr, String javaType, HeaderRole role) {
        return switch (javaType) {
            case "byte" -> "narrowToByte(" + expr + ", \"" + role + "\")";
            case "short" -> "narrowToShort(" + expr + ", \"" + role + "\")";
            default -> expr;
        };
    }

    // ---- writing -----------------------------------------------------------------------------------------------

    private void writeBody() {
        line("@Override");
        line("protected void writeBody(" + RT + "IbWriter w, " + m.javaName() + " v) {");
        indent++;
        List<FieldModel> fields = m.fields();
        for (FieldModel f : fields) {
            line(f.type().javaName() + " " + local(f) + " = v." + f.accessor() + "();");
            if (f.nonNullDeclared()) {
                line("if (" + local(f) + " == null) throw " + RT + "IntrabufException.nullField(" + quote(path(f)) + ");");
            }
        }
        int bits = layout.bitCount(m.minor());
        int nb = layout.bitsetBytes(m.minor());
        if (bits > 0) {
            for (int w = 0; w < words(bits); w++) {
                line("long b$" + w + " = 0L;");
            }
            for (int i = 0; i < fields.size(); i++) {
                FieldModel f = fields.get(i);
                String x = local(f);
                boolean optional = f.type().ref() instanceof TypeRef.OptionalOf;
                int pb = layout.presenceBit(i);
                int vb = layout.valueBit(i);
                String present = optional ? x + " != null && " + x + ".isPresent()" : x + " != null";
                if (pb >= 0) {
                    line("if (" + present + ") " + setBit(pb) + ";");
                }
                if (vb >= 0) {
                    String value = optional ? present + " && " + x + ".get()"
                            : pb >= 0 ? present + " && " + x
                            : x;
                    line("if (" + value + ") " + setBit(vb) + ";");
                }
            }
        }
        if (m.compat() == Compat.FULL) {
            line("w.writeVarint(" + nb + ");");
        }
        for (int w = 0; w < words(bits); w++) {
            line("w.writeBits(b$" + w + ", " + Math.min(8, nb - 8 * w) + ");");
        }
        for (int i = 0; i < fields.size(); i++) {
            if (!layout.hasBody(i)) {
                continue;
            }
            FieldModel f = fields.get(i);
            String x = local(f);
            if (f.type().ref() instanceof TypeRef.OptionalOf) {
                JType inner = f.type().arg(0);
                line("if (" + x + " != null && " + x + ".isPresent()) {");
                indent++;
                String o = "o$" + (tmp++);
                line(inner.javaName() + " " + o + " = " + x + ".get();");
                emitWrite(inner, o, path(f));
                indent--;
                line("}");
            } else if (f.nullable()) {
                line("if (" + x + " != null) {");
                indent++;
                emitWrite(f.type(), x, path(f));
                indent--;
                line("}");
            } else {
                emitWrite(f.type(), x, path(f));
            }
        }
        indent--;
        line("}");
    }

    /** Writes the non-null value held in the variable {@code x}. */
    private void emitWrite(JType t, String x, String path) {
        switch (t.ref()) {
            case TypeRef.Scalar s -> line("w.write" + s.kind().methodSuffix() + "(" + x + ");");
            case TypeRef.EnumRef e -> line("w.writeEnum(" + x + ");");
            case TypeRef.MessageRef msg -> line(t.className() + ".CODEC.writeNested(w, " + x + ");");
            case TypeRef.ListOf l -> writeCollection(t, x, path);
            case TypeRef.SetOf s -> writeCollection(t, x, path);
            case TypeRef.MapOf mp -> {
                int n = tmp++;
                JType k = t.arg(0);
                JType v = t.arg(1);
                line("w.writeVarint(" + x + ".size());");
                line("for (java.util.Map.Entry<" + k.javaName() + ", " + v.javaName() + "> e$" + n + " : " + x + ".entrySet()) {");
                indent++;
                line(k.javaName() + " k$" + n + " = e$" + n + ".getKey();");
                line(v.javaName() + " v$" + n + " = e$" + n + ".getValue();");
                line("if (k$" + n + " == null || v$" + n + " == null) throw " + RT + "IntrabufException.nullElement(" + quote(path) + ");");
                emitWrite(k, "k$" + n, path);
                emitWrite(v, "v$" + n, path);
                indent--;
                line("}");
            }
            case TypeRef.OptionalOf o -> throw new IllegalStateException("nested optional");
        }
    }

    private void writeCollection(JType t, String x, String path) {
        int n = tmp++;
        JType e = t.arg(0);
        line("w.writeVarint(" + x + ".size());");
        line("for (" + e.javaName() + " e$" + n + " : " + x + ") {");
        indent++;
        line("if (e$" + n + " == null) throw " + RT + "IntrabufException.nullElement(" + quote(path) + ");");
        emitWrite(e, "e$" + n, path);
        indent--;
        line("}");
    }

    // ---- reading -----------------------------------------------------------------------------------------------

    private void readBody() {
        line("@Override");
        line("protected " + m.javaName() + " readBody(" + RT + "IbReader r, int minor) {");
        indent++;
        List<FieldModel> fields = m.fields();
        int bits = layout.bitCount(m.minor());
        switch (m.compat()) {
            case STRICT -> {
                if (bits > 0) {
                    line("int nb$ = " + layout.bitsetBytes(m.minor()) + ";");
                }
            }
            case BACKWARD -> {
                if (bits > 0) {
                    line("int nb$ = BITSET_BYTES[minor];");
                }
            }
            case FULL -> line("int nb$ = r.readCount();");
        }
        if (bits > 0) {
            line("int at$ = r.beginBits(nb$);");
            for (int w = 0; w < words(bits); w++) {
                line("long b$" + w + " = r.bitsWord(at$, nb$, " + w + ");");
            }
        } else if (m.compat() == Compat.FULL) {
            line("r.skip(nb$); // bits from a newer writer");
        }
        for (int i = 0; i < fields.size(); i++) {
            FieldModel f = fields.get(i);
            String x = local(f);
            boolean optional = f.type().ref() instanceof TypeRef.OptionalOf;
            boolean guarded = m.compat() != Compat.STRICT && f.since() > 0;
            int pb = layout.presenceBit(i);
            int vb = layout.valueBit(i);

            if (!guarded && pb < 0) {
                // Always present: declare and read in one statement.
                if (vb >= 0) {
                    line(f.type().javaName() + " " + x + " = (" + bit(vb) + ") != 0;");
                } else {
                    readInto(f.type(), x);
                }
                continue;
            }
            line(f.type().javaName() + " " + x + " = " + defaultValue(f) + ";");
            if (guarded) {
                line("if (minor >= " + f.since() + ") {");
                indent++;
            }
            if (vb >= 0) {
                String value = "(" + bit(vb) + ") != 0";
                String v = optional ? "java.util.Optional.of(" + value + ")" : value;
                if (pb >= 0) {
                    line("if ((" + bit(pb) + ") != 0) " + x + " = " + v + ";");
                } else {
                    line(x + " = " + v + ";");
                }
            } else if (optional) {
                JType inner = f.type().arg(0);
                line("if ((" + bit(pb) + ") != 0) {");
                indent++;
                String o = readInto(inner, "o$" + (tmp++));
                line(x + " = java.util.Optional.of(" + o + ");");
                indent--;
                line("}");
            } else if (pb >= 0) {
                line("if ((" + bit(pb) + ") != 0) {");
                indent++;
                emitRead(f.type(), x);
                indent--;
                line("}");
            } else {
                emitRead(f.type(), x);
            }
            if (guarded) {
                indent--;
                line("}");
            }
        }
        StringBuilder args = new StringBuilder();
        for (FieldModel f : fields) {
            args.append(args.isEmpty() ? "" : ", ").append(local(f));
        }
        line("return new " + m.javaName() + "(" + args + ");");
        indent--;
        line("}");
    }

    /** An expression reading a value of {@code t}, or null if it needs statements (collections). */
    private String readExpr(JType t) {
        return switch (t.ref()) {
            case TypeRef.Scalar s -> "r.read" + s.kind().methodSuffix() + "()";
            case TypeRef.EnumRef e -> {
                String table = enumFields.computeIfAbsent(t.className(), k -> "ENUM$" + enumFields.size());
                yield table + "[r.readEnum(" + table + ".length, " + quote(e.name()) + ")]";
            }
            case TypeRef.MessageRef msg -> t.className() + ".CODEC.readNested(r)";
            default -> null;
        };
    }

    /** Assigns a value of {@code t} read from {@code r} to the already-declared variable {@code target}. */
    private void emitRead(JType t, String target) {
        String expr = readExpr(t);
        if (expr != null) {
            line(target + " = " + expr + ";");
            return;
        }
        int n = tmp++;
        String count = "n$" + n;
        String coll = "c$" + n;
        line("{");
        indent++;
        line("int " + count + " = r.readCount();");
        switch (t.ref()) {
            case TypeRef.ListOf l -> line("java.util.ArrayList<" + t.arg(0).javaName() + "> " + coll
                    + " = new java.util.ArrayList<>(r.capacityHint(" + count + "));");
            case TypeRef.SetOf s -> line("java.util.LinkedHashSet<" + t.arg(0).javaName() + "> " + coll
                    + " = java.util.LinkedHashSet.newLinkedHashSet(r.capacityHint(" + count + "));");
            case TypeRef.MapOf mp -> line("java.util.LinkedHashMap<" + t.arg(0).javaName() + ", " + t.arg(1).javaName() + "> "
                    + coll + " = java.util.LinkedHashMap.newLinkedHashMap(r.capacityHint(" + count + "));");
            default -> throw new IllegalStateException(t.ref().toString());
        }
        line("for (int i$" + n + " = 0; i$" + n + " < " + count + "; i$" + n + "++) {");
        indent++;
        if (t.ref() instanceof TypeRef.MapOf) {
            String k = readInto(t.arg(0), "k$" + n);
            String v = readInto(t.arg(1), "v$" + n);
            line(coll + ".put(" + k + ", " + v + ");");
        } else {
            line(coll + ".add(" + readInto(t.arg(0), "x$" + n) + ");");
        }
        indent--;
        line("}");
        line(target + " = " + coll + ";");
        indent--;
        line("}");
    }

    /** Reads a value of {@code t}, returning an expression for it: inline if simple, else via a fresh local. */
    private String readInto(JType t, String name) {
        String expr = readExpr(t);
        if (expr != null) {
            // Map keys and values must be read in order, so a key expression cannot be inlined into put() next to
            // its value's statements; hold simple values in a local too when the other side needs statements.
            line(t.javaName() + " " + name + " = " + expr + ";");
            return name;
        }
        line(t.javaName() + " " + name + ";");
        emitRead(t, name);
        return name;
    }

    private String defaultValue(FieldModel f) {
        TypeRef t = f.type().ref();
        if (t instanceof TypeRef.OptionalOf) {
            return "java.util.Optional.empty()";
        }
        if (t instanceof TypeRef.Scalar && f.type().javaName().indexOf('.') < 0 && !t.isScalar(ScalarKind.BYTES)) {
            return t.isScalar(ScalarKind.BOOL) ? "false" : "0";
        }
        if (f.nullable()) {
            return "null";
        }
        return switch (t) {
            case TypeRef.ListOf l -> "new java.util.ArrayList<>()";
            case TypeRef.SetOf s -> "new java.util.LinkedHashSet<>()";
            case TypeRef.MapOf mp -> "new java.util.LinkedHashMap<>()";
            default -> t.isScalar(ScalarKind.STRING) ? "\"\""
                    : t.isScalar(ScalarKind.BYTES) ? "new byte[0]"
                    : t.isScalar(ScalarKind.BOOL) ? "false"
                    : "null"; // non-null, but always read: an initializer the compiler needs, never the value
        };
    }

    // ---- helpers -----------------------------------------------------------------------------------------------

    private static int words(int bits) {
        return (bits + 63) >>> 6;
    }

    private static String mask(int bit) {
        return "0x" + Long.toHexString(1L << (bit & 63)) + "L";
    }

    private static String setBit(int bit) {
        return "b$" + (bit >>> 6) + " |= " + mask(bit);
    }

    private static String bit(int bit) {
        return "b$" + (bit >>> 6) + " & " + mask(bit);
    }

    private static String local(FieldModel f) {
        return "f_" + f.name();
    }

    private String path(FieldModel f) {
        return m.javaName() + "." + f.name();
    }

    private void line(String s) {
        if (!s.isEmpty()) {
            sb.repeat("    ", indent).append(s);
        }
        sb.append('\n');
    }
}
