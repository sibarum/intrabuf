package sibarum.intrabuf.processor;

import sibarum.intrabuf.Hex;
import sibarum.intrabuf.processor.MessageModel.FieldModel;

import static sibarum.intrabuf.schema.Json.quote;

/**
 * Writes the source of one bundle codec: the schema constants, a {@code Visitor} and a {@code Writer} with one method
 * per member, and the three methods {@link sibarum.intrabuf.BundleCodec} leaves to it. The rows themselves are
 * written and read by the members' own codecs.
 */
final class BundleGenerator {

    private static final String RT = "sibarum.intrabuf.";

    private final MessageModel m;
    private final int fingerprint;
    private final boolean snapshot;
    private final String buildVersion;
    private final StringBuilder sb = new StringBuilder();
    private int indent;

    BundleGenerator(MessageModel m, int fingerprint, boolean snapshot, String buildVersion) {
        this.m = m;
        this.fingerprint = fingerprint;
        this.snapshot = snapshot;
        this.buildVersion = buildVersion;
    }

    String generate() {
        String type = m.javaName();
        String self = m.codecSimpleName();
        if (!m.packageName().isEmpty()) {
            line("package " + m.packageName() + ";");
            line("");
        }
        line("/**");
        line(" * Codec for {@link " + type + "}: bundle {@code " + m.schemaName() + "} v" + m.major() + "." + m.minor()
                + ", " + m.compat() + ", written as a text log.");
        line(" * Generated by intrabuf; do not edit.");
        line(" */");
        line("@javax.annotation.processing.Generated(\"sibarum.intrabuf.processor.IntrabufProcessor\")");
        line("public final class " + self + " extends " + RT + "BundleCodec<" + type + ", " + self + ".Visitor> {");
        indent++;
        line("");
        line("public static final String NAME = " + quote(m.schemaName()) + ";");
        line("public static final int ID = " + Hex.int32(m.id()) + ";");
        line("public static final int MAJOR = " + m.major() + ";");
        line("public static final int MINOR = " + m.minor() + ";");
        line("public static final int FINGERPRINT = " + Hex.int32(fingerprint) + ";");
        line("public static final boolean SNAPSHOT = " + snapshot + ";");
        line("public static final String BUILD_VERSION = " + quote(buildVersion) + ";");
        line("");
        line("public static final " + RT + "SchemaInfo SCHEMA = new " + RT + "SchemaInfo(NAME, " + quote(type)
                + ", ID, MAJOR, MINOR, " + RT + "Compat." + m.compat() + ", FINGERPRINT, SNAPSHOT, BUILD_VERSION);");
        line("");
        line("public static final " + self + " CODEC = new " + self + "();");
        line("");
        line("private " + self + "() {");
        indent++;
        line("super(SCHEMA, new " + RT + "BundleCodec.Member[]{");
        for (FieldModel f : m.fields()) {
            line("        new " + RT + "BundleCodec.Member(" + quote(f.name()) + ", " + codec(f) + ".CODEC, " + f.since() + "),");
        }
        line("});");
        indent--;
        line("}");
        line("");

        line("/** Receives a log's rows as they are read, one method per member. Each does nothing unless overridden. */");
        line("public interface Visitor {");
        for (FieldModel f : m.fields()) {
            line("    default void " + f.name() + "(" + row(f) + " row) {");
            line("    }");
            line("");
        }
        trimBlank();
        line("}");
        line("");

        line("/** Appends rows to a log as they happen, one method per member. See {@link " + RT + "LogWriter}. */");
        line("public static final class Writer extends " + RT + "LogWriter {");
        indent++;
        line("private Writer(java.lang.Appendable out) {");
        line("    super(CODEC, out);");
        line("}");
        for (int i = 0; i < m.fields().size(); i++) {
            FieldModel f = m.fields().get(i);
            line("");
            line("public void " + f.name() + "(" + row(f) + " row) {");
            line("    write(" + i + ", row);");
            line("}");
        }
        indent--;
        line("}");
        line("");

        line("/** Starts a log on {@code out}: writes the facts line and every member's declaration. */");
        line("public static Writer writer(java.lang.Appendable out) {");
        line("    return new Writer(out);");
        line("}");
        line("");
        line("/** The whole bundle as a text log. Same as {@code CODEC.encodeText(value)}. */");
        line("public static String toText(" + type + " value) {");
        line("    return CODEC.encodeText(value);");
        line("}");
        line("");
        line("/** Decodes a whole text log. Same as {@code CODEC.decodeText(log)}. */");
        line("public static " + type + " fromText(String log) {");
        line("    return CODEC.decodeText(log);");
        line("}");
        line("");
        line("/** Decodes a whole text log given as UTF-8. Same as {@code CODEC.decode(payload)}. */");
        line("public static " + type + " fromBytes(byte[] payload) {");
        line("    return CODEC.decode(payload);");
        line("}");
        line("");

        StringBuilder args = new StringBuilder();
        for (int i = 0; i < m.fields().size(); i++) {
            args.append(i == 0 ? "" : ", ").append("(java.util.List<").append(row(m.fields().get(i))).append(">) l$[")
                    .append(i).append(']');
        }
        line("@Override");
        line("@SuppressWarnings(\"unchecked\")");
        line("protected " + type + " create(java.util.List<?>[] l$) {");
        line("    return new " + type + "(" + args + ");");
        line("}");
        line("");
        line("@Override");
        line("protected java.util.List<?> list(" + type + " v, int member$) {");
        indent++;
        line("return switch (member$) {");
        for (int i = 0; i < m.fields().size(); i++) {
            line("    case " + i + " -> v." + m.fields().get(i).accessor() + "();");
        }
        line("    default -> throw new IllegalArgumentException(\"no member \" + member$);");
        line("};");
        indent--;
        line("}");
        line("");
        line("@Override");
        line("protected void dispatch(Visitor visitor, int member$, Object row$) {");
        indent++;
        line("switch (member$) {");
        for (int i = 0; i < m.fields().size(); i++) {
            FieldModel f = m.fields().get(i);
            line("    case " + i + " -> visitor." + f.name() + "((" + row(f) + ") row$);");
        }
        line("    default -> throw new IllegalArgumentException(\"no member \" + member$);");
        line("}");
        indent--;
        line("}");
        indent--;
        line("}");
        return sb.toString();
    }

    /** The message type a member's rows are. */
    private static String row(FieldModel f) {
        return f.type().arg(0).javaName();
    }

    /** The codec class of a member's rows. */
    private static String codec(FieldModel f) {
        return f.type().arg(0).className();
    }

    private void trimBlank() {
        if (sb.length() >= 2 && sb.charAt(sb.length() - 1) == '\n' && sb.charAt(sb.length() - 2) == '\n') {
            sb.setLength(sb.length() - 1);
        }
    }

    private void line(String s) {
        if (!s.isEmpty()) {
            sb.repeat("    ", indent).append(s);
        }
        sb.append('\n');
    }
}
